OTHER_DIFF_R2 = -3  # 「その他」の列の増減（合計の検算用）


def build():
    n = len(NAMES)
    for name, arr in (("TOTAL", TOTAL), ("TOTAL_DIFF_R2", TOTAL_DIFF_R2), ("TEMP", TEMP), ("OUTSIDE", OUTSIDE),
                      ("UNASSIGNED", UNASSIGNED)):
        if len(arr) != n:
            raise SystemExit(f"{name}: {len(arr)} 件（自治体は {n}）")
    for i in range(n):
        if TEMP[i] + OUTSIDE[i] != TOTAL[i]:
            raise SystemExit(f"{NAMES[i]}: 臨時{TEMP[i]}+免許外{OUTSIDE[i]} != 計{TOTAL[i]}")
    checks = [
        (sum(TOTAL), TABLE_TOTALS["計"], "計"),
        (sum(TEMP), TABLE_TOTALS["臨時免許状"], "臨時免許状"),
        (sum(OUTSIDE), TABLE_TOTALS["免許外教科担任"], "免許外教科担任"),
        (sum(TOTAL_DIFF_R2) + OTHER_DIFF_R2, TABLE_TOTALS["計のR2増減"], "計のR2増減"),
        (sum(UNASSIGNED) + UNASSIGNED_OTHER, TABLE_TOTALS["未担当"], "未担当"),
        (sum(PLAN_R5.values()), TABLE_TOTALS["R5見込み"], "R5見込み"),
    ]
    for got, want, label in checks:
        if got != want:
            raise SystemExit(f"{label}: 合計 {got} != 表の合計 {want}")
    # 3ページの図の棒との照合（読み取った例）: 長野県は免許外のみ76、栃木県は臨時45＋免許外23、鹿児島県は臨時のみ35
    ex = {NAMES[i]: (TEMP[i], OUTSIDE[i]) for i in range(n)}
    assert ex["長野県"] == (0, 76) and ex["栃木県"] == (45, 23) and ex["鹿児島県"] == (35, 0) and ex["高知県"] == (1, 25)
    assert set(PLAN_R5) <= set(NAMES)
    rows = []
    for i, name in enumerate(NAMES):
        rows.append({
            "自治体": name,
            "臨時免許状": TEMP[i],
            "免許外教科担任": OUTSIDE[i],
            "臨時免許状・免許外教科担任の計": TOTAL[i],
            "計の令和2年調査からの増減": TOTAL_DIFF_R2[i],
            "令和5年4月見込み（改善計画の履行後）": PLAN_R5.get(name, 0),
            "情報免許状保有で情報科を担当していない者": UNASSIGNED[i],
        })
    return rows


