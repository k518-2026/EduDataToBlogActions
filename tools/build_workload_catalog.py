def minutes(s: str) -> int:
    m = re.fullmatch(r"([+\-−±]?)(\d+):(\d\d)", s)
    if not m:
        raise ValueError(s)
    sign = -1 if m.group(1) in ("-", "−") else 1
    return sign * (int(m.group(2)) * 60 + int(m.group(3)))


def build():
    assert list(WEEKDAY) == list(HOLIDAY), "平日と土日の業務の並びが違う"
    rows = []
    problems = []
    for task in WEEKDAY:
        row = {"業務内容": task}
        for day, table in (("平日", WEEKDAY), ("土日", HOLIDAY)):
            v = table[task]
            for i, school in enumerate(("小学校", "中学校")):
                h28, r4, diff = (minutes(x) for x in v[i * 3: i * 3 + 3])
                if abs((r4 - h28) - diff) > 1:
                    problems.append(f"{day} {school} {task}: {h28}→{r4} だが増減 {diff}")
                row[f"{day}・{school}・平成28年度"] = h28
                row[f"{day}・{school}・令和4年度"] = r4
                row[f"{day}・{school}・増減"] = diff
        rows.append(row)
    if problems:
        raise SystemExit("転記の検査に失敗:\n" + "\n".join(problems))
    return rows


